"""
Writes src/test/data/pq_wallet_vectors.json, the golden vector of the wallet's post-quantum key
derivation (docs/plans/yellowback-quantum-spec.md ruling A-12): HKDF-SHA256 (RFC 5869) with
IKM = the wallet seed, salt empty, info = "Ycash PQ key" (12 ASCII bytes) || scheme u8 ||
index u32 big-endian, L = 48, then the scheme's KeyGen from those 48 bytes.

src/test/pq_wallet_tests.cpp replays it against the C++ (on both node lines) and clients copy it
byte for byte (YEW core/tests/vectors/, pinned and compared in its CI); the file must be
byte-identical on ycash-dd and ycash6. Pure Python: hmac/hashlib HKDF and PBKDF2, and
test_framework/pq.py's FIPS 205 slh_keygen, independent of the C++ it checks.

    .venv/bin/python qa/rpc-tests/test_framework/gen_pq_wallet_vectors.py           # write
    .venv/bin/python qa/rpc-tests/test_framework/gen_pq_wallet_vectors.py --check   # compare only

JSON (every byte string lowercase hex):

    _comment                 text
    format                   "ycash-pq-wallet-vectors-1"
    info                     "Ycash PQ key"
    hdSeed                   the ycash-dd (v4.5.0) wallet: IKM = HDSeed::RawSeed(), 32 bytes
      {ikm, derive[] {scheme, index, seed (48)}, slh {index, pk (32), keyhash (32)}}
    mnemonic                 the ycash6 (6.20.0) wallet and YEW: IKM = the BIP39 seed of the
                             24-word English phrase, empty passphrase (PBKDF2-HMAC-SHA512,
                             salt "mnemonic", 2048 rounds), 64 bytes
      {entropy (32), phrase, ikm (64), derive[], slh}

The phrase is the BIP39 English encoding of `entropy`; it is input data here (no wordlist in the
framework) and checked by ycash6's MnemonicSeed::FromEntropy and by YEW's bip39 crate.
"""

import hashlib
import hmac
import json
import os
import sys

if __name__ == '__main__':
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.realpath(__file__)), '..'))

from test_framework import pq    # noqa: E402

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.realpath(__file__)), '..', '..', '..'))
OUT = os.path.join(ROOT, 'src', 'test', 'data', 'pq_wallet_vectors.json')

INFO = b'Ycash PQ key'
SEED_SIZE = 48
# (scheme, index) pairs every implementation reproduces.
DERIVE = [(1, 0), (1, 1), (2, 0), (2, 1)]

# The test seed of both node lines' pq_wallet_tests: bytes 0x00..0x1f (ycash-dd's raw HD seed;
# ycash6's mnemonic entropy).
TEST_SEED = bytes(range(32))
TEST_PHRASE = ('abandon amount liar amount expire adjust cage candy arch gather drum bullet absurd math era '
               'live bid rhythm alien crouch range attend journey unaware')


def hkdf_sha256(ikm, info, length, salt=b''):
    prk = hmac.new(salt or bytes(32), ikm, hashlib.sha256).digest()
    out, t, counter = b'', b'', 1
    while len(out) < length:
        t = hmac.new(prk, t + info + bytes([counter]), hashlib.sha256).digest()
        out += t
        counter += 1
    return out[:length]


def derive_pq_seed(ikm, scheme, index):
    return hkdf_sha256(ikm, INFO + bytes([scheme]) + index.to_bytes(4, 'big'), SEED_SIZE)


def _section(ikm):
    derive = [{'scheme': s, 'index': i, 'seed': derive_pq_seed(ikm, s, i).hex()} for s, i in DERIVE]
    pk, _ = pq.slh_keygen(derive_pq_seed(ikm, 1, 0))
    return {'ikm': ikm.hex(), 'derive': derive,
            'slh': {'index': 0, 'pk': pk.hex(), 'keyhash': pq.key_hash(1, pk).hex()}}


def build():
    bip39_seed = hashlib.pbkdf2_hmac('sha512', TEST_PHRASE.encode(), b'mnemonic', 2048)
    mnemonic = {'entropy': TEST_SEED.hex(), 'phrase': TEST_PHRASE}
    mnemonic.update(_section(bip39_seed))
    return {
        '_comment': 'Generated by qa/rpc-tests/test_framework/gen_pq_wallet_vectors.py; do not edit. '
                    'Quantum spec A-12: HKDF-SHA256(IKM = wallet seed, salt empty, info = "Ycash PQ key" || '
                    'scheme || index_be32, L = 48). hdSeed: the v4.5.0 node line (32-byte HD seed); mnemonic: the 6.20.0 node line and YEW '
                    '(64-byte BIP39 seed, empty passphrase).',
        'format': 'ycash-pq-wallet-vectors-1',
        'info': INFO.decode(),
        'hdSeed': _section(TEST_SEED),
        'mnemonic': mnemonic,
    }


def dumps(doc):
    return json.dumps(doc, indent=1, sort_keys=False) + '\n'


def main():
    text = dumps(build())
    if '--check' in sys.argv[1:]:
        with open(OUT) as f:
            if f.read() != text:
                print('pq_wallet_vectors.json is stale; rerun without --check')
                return 1
        print('pq_wallet_vectors.json up to date')
        return 0
    with open(OUT, 'w') as f:
        f.write(text)
    print('wrote', OUT)
    return 0


if __name__ == '__main__':
    sys.exit(main())
